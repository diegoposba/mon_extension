from qgis.PyQt.QtCore import QLocale, QTranslator, QCoreApplication
from qgis.core import QgsSettings, QgsProject, QgsVectorLayer, QgsWkbTypes, QgsCoordinateReferenceSystem, QgsCoordinateTransform, QgsGeometry, Qgis, QgsFeature, QgsFillSymbol
from qgis.gui import QgsMapToolEmitPoint
from qgis.PyQt.QtGui import QIcon
from qgis.PyQt.QtWidgets import QAction

# Import the code for the dialog
from .mon_extension_dialog import MonExtensionDialog
import os.path
import requests


class MonExtension:
    """QGIS Plugin Implementation."""

    def __init__(self, iface):
        """Constructor.

        :param iface: An interface instance that will be passed to this class
            which provides the hook by which you can manipulate the QGIS
            application at run time.
        :type iface: QgsInterface
        """
        # Save reference to the QGIS interface
        self.iface = iface
        # initialize plugin directory
        self.plugin_dir = os.path.dirname(__file__)
        # initialize locale
        locale = QgsSettings().value('locale/userLocale', QLocale().name())[0:2]
        locale_path = os.path.join(
            self.plugin_dir,
            'i18n',
            '{}.qm'.format(locale))

        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)

        # Declare instance attributes
        self.actions = []
        self.menu = self.tr(u'&TSIPyQGIS')

        # Check if plugin was started the first time in current QGIS session
        # Must be set in initGui() to survive plugin reloads
        self.first_start = None

    # noinspection PyMethodMayBeStatic
    def tr(self, message):
        """Get the translation for a string using Qt translation API.

        We implement this ourselves since we do not inherit QObject.

        :param message: String for translation.
        :type message: str, QString

        :returns: Translated version of message.
        :rtype: QString
        """
        # noinspection PyTypeChecker,PyArgumentList,PyCallByClass
        return QCoreApplication.translate('MonExtension', message)


    def add_action(
        self,
        icon_path,
        text,
        callback,
        enabled_flag=True,
        add_to_menu=True,
        add_to_toolbar=True,
        status_tip=None,
        whats_this=None,
        parent=None):
        """Add a toolbar icon to the toolbar.

        :param icon_path: Path to the icon for this action. Can be a resource
            path (e.g. ':/plugins/foo/bar.png') or a normal file system path.
        :type icon_path: str

        :param text: Text that should be shown in menu items for this action.
        :type text: str

        :param callback: Function to be called when the action is triggered.
        :type callback: function

        :param enabled_flag: A flag indicating if the action should be enabled
            by default. Defaults to True.
        :type enabled_flag: bool

        :param add_to_menu: Flag indicating whether the action should also
            be added to the menu. Defaults to True.
        :type add_to_menu: bool

        :param add_to_toolbar: Flag indicating whether the action should also
            be added to the toolbar. Defaults to True.
        :type add_to_toolbar: bool

        :param status_tip: Optional text to show in a popup when mouse pointer
            hovers over the action.
        :type status_tip: str

        :param parent: Parent widget for the new action. Defaults None.
        :type parent: QWidget

        :param whats_this: Optional text to show in the status bar when the
            mouse pointer hovers over the action.

        :returns: The action that was created. Note that the action is also
            added to self.actions list.
        :rtype: QAction
        """

        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        if status_tip is not None:
            action.setStatusTip(status_tip)

        if whats_this is not None:
            action.setWhatsThis(whats_this)

        if add_to_toolbar:
            # Adds plugin icon to Plugins toolbar
            self.iface.addToolBarIcon(action)

        if add_to_menu:
            self.iface.addPluginToMenu(
                self.menu,
                action)

        self.actions.append(action)

        return action

    def initGui(self):
        """Create the menu entries and toolbar icons inside the QGIS GUI."""

        icon_path = os.path.join(os.path.dirname(__file__), 'icon.png')
        self.add_action(
            icon_path,
            text=self.tr(u'TP M2 TSI PyQGIS'),
            callback=self.run,
            parent=self.iface.mainWindow())

        # will be set False in run()
        self.first_start = True


    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""
        for action in self.actions:
            self.iface.removePluginMenu(
                self.tr(u'&TSIPyQGIS'),
                action)
            self.iface.removeToolBarIcon(action)
        if self.first_start is False:
            self.canvas.unsetMapTool(self.pointTool)

    def displayPoint(self, point, button):
        """US2 : affiche le point clique (QgsPointXY) en WGS 84"""
        crs_carte = self.canvas.mapSettings().destinationCrs()
        crs_wgs84 = QgsCoordinateReferenceSystem("EPSG:4326")
        transform = QgsCoordinateTransform(crs_carte, crs_wgs84, QgsProject.instance())
        point_wgs84 = transform.transform(point)
        self.dlg.lbl_longitude.setText(f"{point_wgs84.x():.5f}")
        self.dlg.lbl_latitude.setText(f"{point_wgs84.y():.5f}")

        # US3 : adresse BAN la plus proche
        reponse = requests.get("https://data.geopf.fr/geocodage/reverse", params={
            "lat": point_wgs84.y(),
            "lon": point_wgs84.x(),
            "type": "housenumber",
            "limit": 1,
        })
        resultats = reponse.json()["features"]
        if resultats:
            adresse = resultats[0]["properties"]
            self.dlg.lbl_adresse.setText(
                f"{adresse['housenumber']} {adresse['street']}, {adresse['citycode']} {adresse['city']}")
        else:
            self.dlg.lbl_adresse.setText("Aucune adresse trouvée")

        # US4 : nombre d'objets de la couche selectionnee a moins de X mètres
        distance = self.dlg.le_distance.text()
        if not distance.isdigit():
            self.iface.messageBar().pushMessage("Erreur", "La distance doit être un nombre entier", level=Qgis.Critical)
            return
        # zone tampon calculee en Lambert 93
        crs_l93 = QgsCoordinateReferenceSystem("EPSG:2154")
        point_l93 = QgsCoordinateTransform(crs_carte, crs_l93, QgsProject.instance()).transform(point)
        tampon = QgsGeometry.fromPointXY(point_l93).buffer(int(distance), 20)

        # US5 : afficher la zone tampon dans une couche temporaire
        zones = QgsProject.instance().mapLayersByName("Zone tampon")
        if zones:
            zone = zones[0]
        else:
            zone = QgsVectorLayer("Polygon?crs=EPSG:2154", "Zone tampon", "memory")
            symbole = QgsFillSymbol.createSimple({"color": "0,0,0,0", "outline_color": "#000000", "outline_width": "0.26"})
            zone.renderer().setSymbol(symbole)
            QgsProject.instance().addMapLayer(zone, False)
            QgsProject.instance().layerTreeRoot().insertLayer(0, zone)
        zone.dataProvider().deleteFeatures(zone.allFeatureIds())  
        objet_zone = QgsFeature()
        objet_zone.setGeometry(tampon)
        zone.dataProvider().addFeatures([objet_zone])
        zone.triggerRepaint()

        # US4 : compter les objets de la couche selectionnee dans la zone tampon
        couches = QgsProject.instance().mapLayersByName(self.dlg.cb_couches.currentText())
        if not couches:
            return
        couche = couches[0]
        tampon = QgsGeometry(tampon)  # copie, pour ne pas modifier la geometrie affichee
        tampon.transform(QgsCoordinateTransform(crs_l93, couche.crs(), QgsProject.instance()))
        nb_objets = 0
        for objet in couche.getFeatures():
            if objet.geometry().intersects(tampon):
                nb_objets += 1
        self.dlg.lbl_nb_objets.setText(str(nb_objets))


    def run(self):
        """Run method that performs all the real work"""

        # Create the dialog with elements (after translation) and keep reference
        # Only create GUI ONCE in callback, so that it will only load when the plugin is started
        if self.first_start == True:
            self.first_start = False
            self.dlg = MonExtensionDialog()
            # US2 : clique sur la carte
            self.canvas = self.iface.mapCanvas()
            self.pointTool = QgsMapToolEmitPoint(self.canvas)
            self.pointTool.canvasClicked.connect(self.displayPoint)

        # US1 : liste des couches ponctuelles du projet
        self.dlg.cb_couches.clear()
        for couche in QgsProject.instance().mapLayers().values():
            if isinstance(couche, QgsVectorLayer) and couche.geometryType() == QgsWkbTypes.PointGeometry:
                self.dlg.cb_couches.addItem(couche.name())

        # US2 : clique sur la carte
        self.canvas.setMapTool(self.pointTool)
        self.dlg.show()
